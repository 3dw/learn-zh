/** 取得指定年級（含）以下所有年級的詞庫，已彙整去除重複。 */
export function getWordPool(grade: number): string[] {
	const pool: string[] = []
	for (let g = 1; g <= grade; g++) {
		const words = GRADE_WORDS[g]
		if (words) pool.push(...words)
	}
	return pool
}
